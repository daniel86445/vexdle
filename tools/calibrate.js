// Simulates rolls to give every combo a fixed XP value based on how rare it is,
// then sets the award-tier score cutoffs. Writes js/combo-xp.js.
// Usage: node tools/calibrate.js [rolls]
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const ROOT = path.join(__dirname, '..');
const ctx = { window: {} };
ctx.globalThis = ctx.window;
vm.createContext(ctx);
for (const f of ['js/items.js', 'js/xp.js', 'js/combos.js']) vm.runInContext(fs.readFileSync(path.join(ROOT, f), 'utf8').replace(/typeof window !== 'undefined' \? window : globalThis/, 'window'), ctx);
const W = ctx.window;
const ITEMS = W.VEX_ITEMS, COMBOS = W.VEX_COMBOS, buildCtx = W.VEX_buildCtx;

// sanity: every id string referenced in combos.js must exist
const src = fs.readFileSync(path.join(ROOT, 'js/combos.js'), 'utf8');
const ids = new Set(ITEMS.map(i => i.id));
const refs = [...src.matchAll(/(?:has|cnt)\('([a-z0-9-]+)'\)|i\.id === '([a-z0-9-]+)'/g)].map(m => m[1] || m[2]);
const listRefs = [...src.matchAll(/\[((?:'[a-z0-9-]+',?\s*)+)\]\.every\(c\.has\)/g)].flatMap(m => [...m[1].matchAll(/'([a-z0-9-]+)'/g)].map(x => x[1]));
const missing = [...new Set([...refs, ...listRefs])].filter(r => !ids.has(r));
if (missing.length) { console.error('Unknown item ids in combos.js:', missing); process.exit(1); }
const cids = COMBOS.map(c => c.id); const dup = cids.filter((x, k) => cids.indexOf(x) !== k);
if (dup.length) { console.error('Duplicate combo ids', dup); process.exit(1); }

// pool: every item once, Empty three times
const EMPTY = ITEMS.find(i => i.cat === 'empty');
const POOL = ITEMS.filter(i => i.cat !== 'empty').concat([EMPTY, EMPTY, EMPTY]);
let seed = 12345;
const rnd = () => { seed = (seed * 1664525 + 1013904223) >>> 0; return seed / 4294967296; };
const FULL = POOL.filter(i => i.cat !== 'empty');
const roll = () => { const out = []; for (let k = 0; k < 6; k++) { const pool = (k === 0 || out[k - 1].cat === 'empty') ? POOL : FULL; out.push(pool[Math.floor(rnd() * pool.length)]); } return out; };

const N = +(process.argv[2] || 300000);
const hits = new Array(COMBOS.length).fill(0);
const rolls = [];
for (let r = 0; r < N; r++) {
  const slots = roll(); const c = buildCtx(slots); const hit = [];
  for (let k = 0; k < COMBOS.length; k++) if (COMBOS[k].test(c)) { hits[k]++; hit.push(k); }
  rolls.push([slots, hit]);
}

// XP from rarity: the harder to get, the more XP. XP grows with 1/p^0.55, so a combo that is
// 100x rarer is worth about 12.6x more. Combos never seen in the sim are treated as rarer than 1 in 2N.
const OVERRIDE = { 'dup-4': 25000, 'dup-5': 100000, 'dup-6': 500000 };
// item-count combos: exact odds. P(empty) per eligible slot = 3/437; k empties then a non-empty.
const pe = 3 / POOL.length;
const fromPx = p => Math.max(5, Math.round(10 / Math.pow(p, 0.55)));
[5, 4, 3, 2].forEach(items => { const k = 6 - items; OVERRIDE['items-' + items] = fromPx(Math.pow(pe, k) * (1 - pe)); });
OVERRIDE['items-1'] = 1000000; OVERRIDE['items-0'] = 2500000;
const xpOf = {};
const fromP = p => Math.max(5, Math.round(10 / Math.pow(p, 0.55)));
COMBOS.forEach((c, k) => {
  if (typeof c.xp === 'number') { xpOf[c.id] = c.xp; return; }
  if (OVERRIDE[c.id] != null) { xpOf[c.id] = OVERRIDE[c.id]; return; }
  xpOf[c.id] = fromP(hits[k] ? hits[k] / N : 1 / (2 * N));
});

// score distribution
const scoreOf = (slots, hit) => slots.reduce((a, i) => a + i.xp, 0) + hit.reduce((a, k) => a + xpOf[COMBOS[k].id], 0);
const scores = rolls.map(([s, h]) => scoreOf(s, h)).sort((a, b) => a - b);
const pct = q => scores[Math.min(scores.length - 1, Math.floor(q * scores.length))];
// Tiers (worst -> best). "Worlds Excellence" is only for the day's #1 roll, so it has no cutoff here.
const TIERS = [
  ['Didn\'t Pass Inspection', 0], ['Sportsmanship', 0.01], ['Energy', 0.10], ['Judges', 0.25], ['Design', 0.45],
  ['Innovate', 0.62], ['Amaze', 0.77], ['Tournament Finalist', 0.88], ['Tournament Champion', 0.95],
  ['Excellence', 0.985], ['World Champion', 0.998],
];
const tiers = TIERS.map(([name, q]) => ({ name, min: q === 0 ? -Infinity : pct(q) }));
for (let k = 1; k < tiers.length; k++) if (tiers[k].min <= tiers[k - 1].min) tiers[k].min = tiers[k - 1].min + 1;

const out = `// Generated by tools/calibrate.js from ${N.toLocaleString()} simulated rolls. Do not edit by hand.
window.VEX_COMBO_XP = ${JSON.stringify(xpOf)};
window.VEX_TIERS = ${JSON.stringify(tiers.map(t => ({ name: t.name, min: t.min === -Infinity ? null : t.min })))};
`;
fs.writeFileSync(path.join(ROOT, 'js/combo-xp.js'), out);

// report
const never = COMBOS.filter((c, k) => hits[k] === 0).map(c => c.id);
console.log(`items ${ITEMS.length} (pool ${POOL.length}), combos ${COMBOS.length}, rolls ${N}`);
console.log('score percentiles', [0.01, 0.1, 0.25, 0.5, 0.75, 0.9, 0.99, 0.999].map(q => `${q}:${pct(q)}`).join(' '), 'min', scores[0], 'max', scores[scores.length - 1]);
console.log('tiers', tiers.map(t => `${t.name}>=${t.min}`).join(' | '));
console.log('avg combos per roll', (rolls.reduce((a, r) => a + r[1].length, 0) / N).toFixed(2));
console.log('never hit in sim', never.length);
const top = COMBOS.map((c, k) => [c.id, hits[k] / N, xpOf[c.id]]).sort((a, b) => b[1] - a[1]).slice(0, 12);
console.log('most common', top.map(t => `${t[0]} ${(t[1] * 100).toFixed(1)}% ${t[2]}xp`).join(', '));
